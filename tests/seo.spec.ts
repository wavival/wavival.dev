import { test, expect } from "@playwright/test";

test("robots.txt allows crawl and points to sitemap-index", async ({ request }) => {
  const res = await request.get("/robots.txt");
  expect(res.status()).toBe(200);
  const body = await res.text();
  expect(body).toMatch(/User-agent:\s*\*/);
  expect(body).toMatch(/Allow:\s*\//);
  expect(body).toMatch(/Sitemap:\s*https:\/\/www\.wavival\.dev\/sitemap-index\.xml/);
});

test("sitemap-index.xml is generated by @astrojs/sitemap", async ({ request }) => {
  const res = await request.get("/sitemap-index.xml");
  expect(res.status()).toBe(200);
  const body = await res.text();
  expect(body).toContain("<sitemapindex");
  expect(body).toContain("https://www.wavival.dev/sitemap-0.xml");
});

test("sitemap lists both ES and EN localized routes", async ({ request }) => {
  const res = await request.get("/sitemap-0.xml");
  expect(res.status()).toBe(200);
  const body = await res.text();
  for (const loc of [
    "https://www.wavival.dev/",
    "https://www.wavival.dev/proyectos/",
    "https://www.wavival.dev/servicios/",
    "https://www.wavival.dev/sobre-mi/",
    "https://www.wavival.dev/contacto/",
    "https://www.wavival.dev/en/",
    "https://www.wavival.dev/en/projects/",
    "https://www.wavival.dev/en/services/",
    "https://www.wavival.dev/en/about/",
    "https://www.wavival.dev/en/contact/",
  ]) {
    expect(body).toContain(`<loc>${loc}</loc>`);
  }
  expect(body).not.toContain("<lastmod>");
});
